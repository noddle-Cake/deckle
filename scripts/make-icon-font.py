#!/usr/bin/env python3
"""Builds Deckle's icon font from Lucide (https://lucide.dev, ISC licence).

Downloads lucide-static at a pinned version, checks it against the npm registry's sha512, reads the font and
its code points straight out of the archive (nothing is extracted to disk), keeps only the icons listed in
src/Deckle.App/Assets/Fonts/lucide-icons.txt, and writes:

  src/Deckle.App/Assets/Fonts/lucide.ttf        the subset font
  src/Deckle.App/Assets/Fonts/LICENSE-lucide.txt
  src/Deckle.App/Controls/LucideKind.g.cs        enum + code points

Needs pyftsubset (pip install fonttools). The outputs are committed, so this only runs when the list changes.
"""
import base64
import hashlib
import io
import json
import subprocess
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

VERSION = "1.57.0"
TARBALL = f"https://registry.npmjs.org/lucide-static/-/lucide-static-{VERSION}.tgz"
INTEGRITY = "sha512-nuf4YoaKt3Pq9scXVQ71SLr0Q1/UZiTcfBBivFsCVL6biAzPplTikVWXLetBmK3oFEJS6f2L1rzgEsoJN/Ce0Q=="

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "src/Deckle.App/Assets/Fonts"
CACHE = ROOT / ".cache/lucide" / f"lucide-static-{VERSION}.tgz"
GENERATED = ROOT / "src/Deckle.App/Controls/LucideKind.g.cs"


def tarball() -> bytes:
    if not CACHE.exists():
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(TARBALL) as response:
            CACHE.write_bytes(response.read())
    data = CACHE.read_bytes()
    digest = "sha512-" + base64.b64encode(hashlib.sha512(data).digest()).decode()
    if digest != INTEGRITY:
        CACHE.unlink()
        sys.exit(f"lucide-static {VERSION}: checksum mismatch ({digest})")
    return data


def member(archive: tarfile.TarFile, name: str) -> bytes:
    file = archive.extractfile(f"package/{name}")
    if file is None:
        sys.exit(f"lucide-static {VERSION}: {name} missing")
    return file.read()


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("-"))


def main() -> int:
    names = [line.strip() for line in (FONTS / "lucide-icons.txt").read_text().splitlines()
             if line.strip() and not line.startswith("#")]
    with tarfile.open(fileobj=io.BytesIO(tarball()), mode="r:gz") as archive:
        codes = json.loads(member(archive, "font/codepoints.json"))
        font = member(archive, "font/lucide.ttf")
        licence = member(archive, "LICENSE")
    missing = [n for n in names if n not in codes]
    if missing:
        sys.exit(f"Not in lucide-static {VERSION}: {', '.join(missing)}")

    with tempfile.TemporaryDirectory() as tmp:
        full = Path(tmp) / "lucide.ttf"
        full.write_bytes(font)
        unicodes = ",".join(f"U+{codes[n]:04X}" for n in names)
        subprocess.run(["pyftsubset", str(full), f"--unicodes={unicodes}", "--layout-features=",
                        "--no-hinting", f"--output-file={FONTS / 'lucide.ttf'}"], check=True)
    (FONTS / "LICENSE-lucide.txt").write_bytes(licence)

    lines = [
        "// <auto-generated> by scripts/make-icon-font.py from lucide-static " + VERSION + "; do not edit. </auto-generated>",
        "namespace Deckle.App.Controls;",
        "",
        "/// <summary>The Lucide icons in Assets/Fonts/lucide.ttf (see lucide-icons.txt).</summary>",
        "public enum LucideKind",
        "{",
        *[f"    {pascal(n)}," for n in names],
        "}",
        "",
        "public static partial class Lucide",
        "{",
        "    private static string Code(LucideKind kind) => kind switch",
        "    {",
        *[f"        LucideKind.{pascal(n)} => \"\\u{codes[n]:04X}\"," for n in names],
        "        _ => \"\",",
        "    };",
        "}",
        "",
    ]
    GENERATED.write_text("\n".join(lines))
    size = (FONTS / "lucide.ttf").stat().st_size
    print(f"lucide-static {VERSION}: {len(names)} icons, lucide.ttf {size // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
